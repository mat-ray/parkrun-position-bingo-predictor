#!/usr/bin/env bash
# Publish the app and/or its data to GitHub Pages, so the installed PWA picks up
# the changes from the stable hosted URL (not from this laptop).
#
# Scope (what gets published):
#   ./publish.sh            # BOTH: ingest + rebuild data, and publish app code
#   ./publish.sh --data     # DATA only: ingest + rebuild; publish data outputs
#   ./publish.sh --app      # APP only: publish app code (no ingest/rebuild)
#
# Modifiers (combine with any scope):
#   --no-push               # do everything except commit/push (local rebuild)
#   --serve                 # after building, serve locally for a preview
#   --serve30               # serve for 30 minutes (1-360)
#   9000                    # a bare number = serve port (implies --serve use)
#
# Examples:
#   ./publish.sh                 # publish everything
#   ./publish.sh --data          # just republish freshly-ingested results
#   ./publish.sh --app           # just republish a UI/code change
#   ./publish.sh --app --no-push # rebuild nothing, stage app, but don't push
#   ./publish.sh --serve         # build, then local preview (no push)
#
# Notes:
#   * A push that touches app/** triggers the GitHub Pages deploy workflow.
#   * When app CODE is in scope, sw.js CACHE_VERSION is auto-bumped so installed
#     PWAs fetch the fresh shell instead of a stale cached copy.
#   * --serve is a LOCAL preview only; it never updates the hosted app.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
PORT=8777
SCOPE="both"         # both | data | app
PUSH=1               # 1 = commit & push (unless --serve/--no-push)
SERVE=0
SERVE_MINUTES=10
BRANCH="main"

# Data build outputs (regenerated by the collector).
DATA_PATHS=(app/data.js app/data app/index.standalone.html)
# App code / shell (hand-edited). index.standalone.html is rebuilt from these,
# so it belongs to BOTH; it's listed under data to avoid double-staging.
APP_PATHS=(app/index.html app/app.js app/style.css app/sw.js \
           app/manifest.webmanifest app/icons)

for arg in "$@"; do
  case "${arg}" in
    --data) SCOPE="data" ;;
    --app)  SCOPE="app" ;;
    --no-push) PUSH=0 ;;
    --serve) SERVE=1; PUSH=0 ;;
    --serve*)
      mins="${arg#--serve}"
      if ! [[ "${mins}" =~ ^[0-9]+$ ]] || [ "${mins}" -lt 1 ] || [ "${mins}" -gt 360 ]; then
        echo "Error: --serveMMM needs an integer 1-360 (got '${mins}')." >&2
        exit 2
      fi
      SERVE=1; PUSH=0; SERVE_MINUTES="${mins}" ;;
    ''|*[!0-9]*)
      echo "Error: unrecognised argument '${arg}'." >&2
      echo "Scopes: --data --app (default both). Modifiers: --no-push --serve[MMM] <port>." >&2
      exit 2 ;;
    *) PORT="${arg}" ;;   # bare integer = serve port
  esac
done

# ---------------------------------------------------------------------------
# Step 1 (data/both only): ingest new downloads and rebuild the bundle.
# The --app scope skips this entirely — a code-only change needs no rebuild.
# ---------------------------------------------------------------------------
if [ "${SCOPE}" != "app" ]; then
  echo "==> Ingesting latestresults/ ..."
  if ! python3 "${HERE}/collector/ingest.py"; then
    echo
    printf "Ingest reported problems above. Continue with the build anyway? [y/N] "
    read -r reply
    case "${reply}" in
      [Yy]*) echo "Continuing." ;;
      *) echo "Aborted — fix the files in latestresults/ and re-run."; exit 1 ;;
    esac
  fi
  echo "==> Rebuilding data bundle..."
  python3 "${HERE}/collector/build.py"
else
  echo "==> App-only: skipping ingest/rebuild."
fi

# ---------------------------------------------------------------------------
# Step 2 (app/both only): bump the service-worker cache version so installed
# PWAs fetch the fresh shell rather than a stale cached copy. Only when app
# CODE is in scope (data-only changes don't alter the cached shell files).
# ---------------------------------------------------------------------------
if [ "${SCOPE}" != "data" ]; then
  SW="${HERE}/app/sw.js"
  cur="$(sed -n 's/.*CACHE_VERSION = "pbp-v\([0-9]\{1,\}\)".*/\1/p' "${SW}")"
  if [ -n "${cur}" ]; then
    next=$((cur + 1))
    # Portable in-place edit (BSD/macOS sed needs the empty -i arg).
    sed -i '' "s/CACHE_VERSION = \"pbp-v${cur}\"/CACHE_VERSION = \"pbp-v${next}\"/" "${SW}"
    echo "==> Bumped service-worker cache: pbp-v${cur} -> pbp-v${next}"
    # The standalone inlines sw-less app code, but rebuild it so it mirrors the
    # current app/ in both scopes that publish code.
    if [ "${SCOPE}" = "app" ]; then
      python3 "${HERE}/collector/build.py" >/dev/null
    fi
  else
    echo "==> Warning: couldn't find CACHE_VERSION in sw.js; not bumping." >&2
  fi
fi

# ---------------------------------------------------------------------------
# --serve: local preview only. Never touches git / the hosted app.
# ---------------------------------------------------------------------------
if [ "${SERVE}" = 1 ]; then
  TIMEOUT=$((SERVE_MINUTES * 60))
  if lsof -ti "tcp:${PORT}" >/dev/null 2>&1; then
    echo "==> Port ${PORT} busy; stopping the old listener."
    kill "$(lsof -ti "tcp:${PORT}")" 2>/dev/null || true
    sleep 1
  fi
  IP="$(ipconfig getifaddr en0 2>/dev/null || ipconfig getifaddr en1 2>/dev/null || echo '<your-laptop-ip>')"
  echo
  echo "==> LOCAL PREVIEW for $((TIMEOUT / 60)) min (Ctrl+C to stop):"
  echo "      http://localhost:${PORT}/"
  echo "      http://${IP}:${PORT}/   (same Wi-Fi)"
  echo "    (This does NOT update the hosted app — run without --serve to publish.)"
  echo
  ( cd "${HERE}/app" && exec python3 -m http.server "${PORT}" ) &
  SERVER_PID=$!
  cleanup() { kill "${SERVER_PID}" 2>/dev/null || true; wait "${SERVER_PID}" 2>/dev/null || true; echo; echo "==> Server stopped."; }
  trap cleanup EXIT INT TERM
  SECONDS_LEFT="${TIMEOUT}"
  while kill -0 "${SERVER_PID}" 2>/dev/null && [ "${SECONDS_LEFT}" -gt 0 ]; do
    sleep 1; SECONDS_LEFT=$((SECONDS_LEFT - 1))
  done
  [ "${SECONDS_LEFT}" -le 0 ] && { echo; echo "==> ${SERVE_MINUTES}-minute limit reached — shutting down."; }
  exit 0
fi

# --no-push: built/staged nothing-to-git; stop here.
if [ "${PUSH}" = 0 ]; then
  echo
  echo "==> Done (not pushing). To publish later: commit app/ and push '${BRANCH}'."
  exit 0
fi

# ---------------------------------------------------------------------------
# Default: commit the in-scope paths and push, triggering a Pages redeploy.
# ---------------------------------------------------------------------------
cd "${HERE}"
if ! git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  echo "Error: not a git repository — can't push." >&2; exit 1
fi
if ! git remote get-url origin >/dev/null 2>&1; then
  echo "Error: no 'origin' remote configured — nothing to push to." >&2; exit 1
fi

# Choose what to stage based on scope.
case "${SCOPE}" in
  data) STAGE=("${DATA_PATHS[@]}") ;;
  app)  STAGE=("${APP_PATHS[@]}") ;;
  both) STAGE=("${DATA_PATHS[@]}" "${APP_PATHS[@]}") ;;
esac
git add "${STAGE[@]}" 2>/dev/null || true

if git diff --cached --quiet; then
  echo
  echo "==> No ${SCOPE} changes to publish — the hosted app is already up to date."
  exit 0
fi

STAMP="$(date '+%Y-%m-%d %H:%M')"
echo "==> Committing ${SCOPE} changes (${STAMP})..."
git commit -q -m "publish(${SCOPE}): ${STAMP}"
echo "==> Pushing to origin/${BRANCH} (triggers GitHub Pages deploy)..."
git push -q origin "${BRANCH}"
echo
echo "==> Published (${SCOPE}). Pages redeploys in ~1-2 min:"
echo "      https://mat-ray.github.io/parkrun-position-bingo-predictor/"
echo "    Relaunch the installed app to pull the update."
